-- HDN-331: four stable rooms, three services, nullable base counts only.
CREATE TABLE guide_worship_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES guide_worship_reports(id) ON DELETE CASCADE,
    room_code VARCHAR(20) NOT NULL CHECK (room_code IN ('MAIN_1F_A','MAIN_1F_B','MAIN_2F_C','PRESCHOOL')),
    service_number INTEGER NOT NULL CHECK (service_number BETWEEN 1 AND 3),
    adult_count INTEGER CHECK (adult_count >= 0),
    school_count INTEGER CHECK (school_count >= 0),
    youth_count INTEGER CHECK (youth_count >= 0),
    CONSTRAINT guide_detail_youth_service CHECK (service_number = 3 OR youth_count IS NULL),
    CONSTRAINT guide_detail_room_service UNIQUE (report_id, room_code, service_number)
);
