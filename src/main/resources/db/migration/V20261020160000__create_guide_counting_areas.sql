-- HDN-331: configurable counting areas reuse physical room master data.
CREATE TABLE guide_counting_areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE DEFAULT gen_random_uuid(),
    room_id BIGINT NOT NULL REFERENCES room(id),
    label VARCHAR(200) NOT NULL CHECK (length(btrim(label)) > 0),
    display_order INTEGER NOT NULL CHECK (display_order >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ
);
CREATE INDEX guide_counting_areas_room ON guide_counting_areas(room_id);
