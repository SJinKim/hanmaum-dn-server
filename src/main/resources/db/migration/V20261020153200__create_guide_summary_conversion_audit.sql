-- HDN-331: one-way, explicitly confirmed summary conversion retains the prior snapshot.
CREATE TABLE guide_summary_conversions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL UNIQUE REFERENCES guide_worship_reports(id) ON DELETE CASCADE,
    source_version BIGINT NOT NULL,
    source_date DATE NOT NULL,
    source_service1_count INTEGER,
    source_service2_count INTEGER,
    source_service3_count INTEGER,
    source_notes TEXT,
    converted_by VARCHAR(255) NOT NULL,
    converted_at TIMESTAMPTZ NOT NULL
);
