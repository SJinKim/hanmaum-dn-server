-- HDN-329: immutable import provenance and guarded batch rollback.
CREATE TABLE guide_import_batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    source_sha256 VARCHAR(64) NOT NULL,
    mapping_version VARCHAR(40) NOT NULL,
    rolled_back_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ
);
CREATE TABLE guide_import_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id BIGINT NOT NULL REFERENCES guide_import_batches(id),
    report_id BIGINT NOT NULL UNIQUE REFERENCES guide_worship_reports(id),
    service_date DATE NOT NULL UNIQUE,
    source_row INTEGER NOT NULL,
    source_data TEXT NOT NULL,
    canonical_sha256 VARCHAR(64) NOT NULL,
    imported_version BIGINT NOT NULL
);
