-- HDN-329: independent aggregate worship reports; no member/check-in linkage.
CREATE TABLE guide_worship_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id UUID NOT NULL UNIQUE,
    service_date DATE NOT NULL,
    service1_count INTEGER CHECK (service1_count >= 0),
    service2_count INTEGER CHECK (service2_count >= 0),
    service3_count INTEGER CHECK (service3_count >= 0),
    notes TEXT,
    version BIGINT NOT NULL DEFAULT 0,
    created_by VARCHAR(255) NOT NULL,
    updated_by VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ,
    deleted_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX guide_worship_reports_active_date ON guide_worship_reports(service_date) WHERE deleted_at IS NULL;
