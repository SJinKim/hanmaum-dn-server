-- HDN-331: freeze membership and labels per report; preserve pre-revision detail matrices.
CREATE TABLE guide_report_areas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL REFERENCES guide_worship_reports(id) ON DELETE CASCADE,
    area_id BIGINT NOT NULL REFERENCES guide_counting_areas(id),
    room_id BIGINT NOT NULL REFERENCES room(id),
    room_name VARCHAR(200) NOT NULL,
    label VARCHAR(200) NOT NULL,
    display_order INTEGER NOT NULL,
    CONSTRAINT guide_report_area_unique UNIQUE(report_id, area_id),
    CONSTRAINT guide_report_area_owner UNIQUE(id, report_id)
);
INSERT INTO guide_report_areas(report_id, area_id, room_id, room_name, label, display_order)
SELECT DISTINCT d.report_id, a.id, a.room_id, r.name, a.label, a.display_order
FROM guide_worship_details d
JOIN (VALUES
    ('MAIN_1F_A', 'e3310000-0000-4000-8000-000000000001'::uuid),
    ('MAIN_1F_B', 'e3310000-0000-4000-8000-000000000002'::uuid),
    ('MAIN_2F_C', 'e3310000-0000-4000-8000-000000000003'::uuid),
    ('PRESCHOOL', 'e3310000-0000-4000-8000-000000000004'::uuid)
) AS old(code, public_id) ON old.code = d.room_code
JOIN guide_counting_areas a ON a.public_id = old.public_id JOIN room r ON r.id = a.room_id;
ALTER TABLE guide_worship_details ADD COLUMN report_area_id BIGINT;
UPDATE guide_worship_details d SET report_area_id = s.id
FROM guide_report_areas s JOIN guide_counting_areas a ON a.id = s.area_id
WHERE s.report_id = d.report_id AND a.public_id = CASE d.room_code
    WHEN 'MAIN_1F_A' THEN 'e3310000-0000-4000-8000-000000000001'::uuid
    WHEN 'MAIN_1F_B' THEN 'e3310000-0000-4000-8000-000000000002'::uuid
    WHEN 'MAIN_2F_C' THEN 'e3310000-0000-4000-8000-000000000003'::uuid
    WHEN 'PRESCHOOL' THEN 'e3310000-0000-4000-8000-000000000004'::uuid END;
ALTER TABLE guide_worship_details ALTER COLUMN report_area_id SET NOT NULL;
ALTER TABLE guide_worship_details ADD CONSTRAINT guide_detail_area_owner
    FOREIGN KEY(report_area_id, report_id) REFERENCES guide_report_areas(id, report_id) ON DELETE CASCADE;
ALTER TABLE guide_worship_details ADD CONSTRAINT guide_detail_area_service UNIQUE(report_area_id, service_number);
-- Retain the legacy column for upgrade compatibility; new writers use report_area_id exclusively.
ALTER TABLE guide_worship_details ALTER COLUMN room_code DROP NOT NULL;
