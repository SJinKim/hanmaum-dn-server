package com.hanmaum.dn.tooling.schema

import kotlin.test.Test
import kotlin.test.assertContains
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertFalse
import kotlin.test.assertTrue

class SchemaMarkdownRendererTest {
    private val hash = "a".repeat(64)

    private val members =
        TableInfo(
            schema = "public",
            name = "members",
            columns =
                listOf(
                    ColumnInfo("id", "bigint", notNull = true, default = null, identity = 'd', generated = null),
                    ColumnInfo("email", "character varying(255)", notNull = false, default = null, identity = null, generated = null),
                    ColumnInfo("balance", "numeric(10,2)", notNull = true, default = "0.00", identity = null, generated = null),
                    ColumnInfo(
                        "status",
                        "character varying(20)",
                        notNull = true,
                        default = "'A|B'::character varying",
                        identity = null,
                        generated = null,
                    ),
                    ColumnInfo("search", "text", notNull = false, default = null, identity = null, generated = "lower((email)::text)"),
                ),
            constraints =
                listOf(
                    ConstraintInfo("members_pkey", "PRIMARY KEY (id)"),
                    ConstraintInfo(
                        "fk_members_group",
                        "FOREIGN KEY (group_id, tenant_id) REFERENCES groups(id, tenant_id) ON UPDATE CASCADE ON DELETE SET NULL",
                    ),
                    ConstraintInfo(
                        "ck_members_status",
                        "CHECK (((status)::text = ANY ((ARRAY['A'::character varying, 'B'::character varying])::text[])))",
                    ),
                ),
            indexes =
                listOf(
                    IndexInfo("ux_members_email_active", "btree (lower((email)::text)) WHERE (deleted_at IS NULL)", unique = true),
                    IndexInfo("idx_members_created", "btree (created_at DESC)", unique = false),
                ),
        )
    private val groups =
        TableInfo(
            "public",
            "groups",
            listOf(
                ColumnInfo(
                    "id",
                    "bigint",
                    notNull = true,
                    default = "nextval('groups_id_seq'::regclass)",
                    identity = null,
                    generated = null,
                ),
            ),
            emptyList(),
            emptyList(),
        )
    private val history =
        TableInfo(
            "public",
            "flyway_schema_history",
            listOf(ColumnInfo("version", "character varying(50)", notNull = false, default = null, identity = null, generated = null)),
            emptyList(),
            emptyList(),
        )

    @Test
    fun `renders type details, nullability, defaults, keys, foreign key actions and partial expression indexes`() {
        val markdown = SchemaMarkdownRenderer.render(SchemaCatalog(listOf(members)), SchemaNotes.EMPTY, hash)

        assertContains(markdown, "- `id` bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY\n")
        assertContains(markdown, "- `email` character varying(255)\n")
        assertContains(markdown, "- `balance` numeric(10,2) NOT NULL DEFAULT `0.00`\n")
        assertContains(markdown, "- `status` character varying(20) NOT NULL DEFAULT `'A|B'::character varying`\n")
        assertContains(markdown, "- `search` text GENERATED ALWAYS AS `lower((email)::text)` STORED\n")
        assertContains(markdown, "- `members_pkey` `PRIMARY KEY (id)`\n")
        assertContains(
            markdown,
            "- `fk_members_group` `FOREIGN KEY (group_id, tenant_id) REFERENCES groups(id, tenant_id) ON UPDATE CASCADE ON DELETE SET NULL`\n",
        )
        assertContains(markdown, "- `ux_members_email_active` UNIQUE `btree (lower((email)::text)) WHERE (deleted_at IS NULL)`\n")
        assertContains(markdown, "- `idx_members_created` `btree (created_at DESC)`\n")
        assertContains(markdown, "$hash`\n- Tabellen: 1 · Spalten: 5\n")
    }

    @Test
    fun `sorts tables, constraints and indexes by name but keeps the column order`() {
        val markdown = SchemaMarkdownRenderer.render(SchemaCatalog(listOf(members, groups)), SchemaNotes.EMPTY, hash)

        assertTrue(markdown.indexOf("## public.groups") < markdown.indexOf("## public.members"))
        assertTrue(markdown.indexOf("`ck_members_status`") < markdown.indexOf("`fk_members_group`"))
        assertTrue(markdown.indexOf("`fk_members_group`") < markdown.indexOf("`members_pkey`"))
        assertTrue(markdown.indexOf("`idx_members_created`") < markdown.indexOf("`ux_members_email_active`"))
        assertTrue(markdown.indexOf("`id` bigint NOT NULL GENERATED") < markdown.indexOf("`email`"))
        assertTrue(markdown.indexOf("`email`") < markdown.indexOf("`balance`"))
    }

    @Test
    fun `gives byte-identical output regardless of input order`() {
        val reordered =
            members.copy(constraints = members.constraints.reversed(), indexes = members.indexes.reversed())

        val first = SchemaMarkdownRenderer.render(SchemaCatalog(listOf(members, groups, history)), SchemaNotes.EMPTY, hash)
        val second = SchemaMarkdownRenderer.render(SchemaCatalog(listOf(history, groups, reordered)), SchemaNotes.EMPTY, hash)

        assertEquals(first, second)
        assertFalse(first.contains('\r'))
        assertTrue(first.endsWith("\n"))
    }

    @Test
    fun `labels the Flyway history as technical`() {
        val markdown = SchemaMarkdownRenderer.render(SchemaCatalog(listOf(history)), SchemaNotes.EMPTY, hash)

        assertContains(markdown, "## public.flyway_schema_history (technisch: Flyway-Verlauf)\n")
    }

    @Test
    fun `places a note verbatim under its table`() {
        val note = "Mitglieder der Gemeinde.\n\n- 소속: verschlüsselt (`work_or_school`)\n  zweite Zeile"
        val notes = SchemaNotes.parse("# Notizen\n\n## public.members\n\n$note\n\n## public.groups\nKleingruppen\n")

        val markdown = SchemaMarkdownRenderer.render(SchemaCatalog(listOf(members, groups)), notes, hash)

        assertContains(markdown, "## public.members\n\n$note\n\n- `id`")
        assertContains(markdown, "## public.groups\n\nKleingruppen\n\n- `id`")
    }

    @Test
    fun `rejects notes for a table that does not exist`() {
        val notes = SchemaNotes.parse("## public.old_members\nveraltet\n")

        val error =
            assertFailsWith<IllegalArgumentException> {
                SchemaMarkdownRenderer.render(SchemaCatalog(listOf(members)), notes, hash)
            }
        assertContains(error.message.orEmpty(), "public.old_members")
    }

    @Test
    fun `keeps backticks and line breaks inside a single code span`() {
        assertEquals("``a `b` c``", SchemaMarkdownRenderer.code("a `b` c"))
        assertEquals("`` `x` ``", SchemaMarkdownRenderer.code("`x`"))
        assertEquals("`CHECK (a > 0 AND b > 0)`", SchemaMarkdownRenderer.code("CHECK (a > 0\n   AND b > 0)"))
    }
}
