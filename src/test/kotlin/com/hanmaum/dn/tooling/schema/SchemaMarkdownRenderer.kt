package com.hanmaum.dn.tooling.schema

/**
 * Renders the catalog as compact Markdown. The output depends only on its inputs, never on the
 * input order, time, locale or connection, so the same migrations always give the same bytes.
 */
object SchemaMarkdownRenderer {
    const val HASH_LABEL = "- Migrations-SHA-256: "
    private const val FLYWAY_HISTORY = "public.flyway_schema_history"

    fun render(
        catalog: SchemaCatalog,
        notes: SchemaNotes,
        migrationHash: String,
    ): String {
        val tables = catalog.tables.sortedWith(compareBy(TableInfo::schema, TableInfo::name))
        notes.requireKnownTables(tables.map(TableInfo::qualifiedName).toSet())

        val out = StringBuilder()
        out.line(
            "<!-- Erzeugt von ./gradlew schemaSnapshot aus den Flyway-Migrationen. Nicht von Hand bearbeiten, siehe docs/db/README.md. -->",
        )
        out.line("# DB-Schema")
        out.line()
        out.line("$HASH_LABEL`$migrationHash`")
        out.line("- Tabellen: ${tables.size} · Spalten: ${tables.sumOf { it.columns.size }}")
        out.line("- Fachliche Notizen: `docs/db/schema-notes.md`")
        out.line(
            "- Spalten ohne `NOT NULL` sind nullable. Indizes, die nur einen Primärschlüssel oder Unique-Constraint tragen, stehen beim Constraint.",
        )
        tables.forEach { out.table(it, notes.byTable[it.qualifiedName]) }
        return out.toString()
    }

    private fun StringBuilder.table(
        table: TableInfo,
        note: String?,
    ) {
        line()
        line("## ${table.qualifiedName}" + if (table.qualifiedName == FLYWAY_HISTORY) " (technisch: Flyway-Verlauf)" else "")
        if (!note.isNullOrBlank()) {
            line()
            line(note)
        }
        line()
        table.columns.forEach { line("- ${column(it)}") }
        val constraints = table.constraints.sortedBy(ConstraintInfo::name)
        if (constraints.isNotEmpty()) {
            line()
            line("Constraints:")
            constraints.forEach { line("- ${code(it.name)} ${code(it.definition)}") }
        }
        val indexes = table.indexes.sortedBy(IndexInfo::name)
        if (indexes.isNotEmpty()) {
            line()
            line("Indizes:")
            indexes.forEach { line("- ${code(it.name)} ${if (it.unique) "UNIQUE " else ""}${code(it.definition)}") }
        }
    }

    private fun column(column: ColumnInfo): String =
        buildList {
            add(code(column.name))
            add(column.type)
            if (column.notNull) add("NOT NULL")
            when (column.identity) {
                'a' -> add("GENERATED ALWAYS AS IDENTITY")
                'd' -> add("GENERATED BY DEFAULT AS IDENTITY")
            }
            column.generated?.let { add("GENERATED ALWAYS AS ${code(it)} STORED") }
            column.default?.let { add("DEFAULT ${code(it)}") }
        }.joinToString(" ")

    /** A code span that survives backticks, Markdown syntax and line breaks in catalog text. */
    internal fun code(text: String): String {
        val flat = text.trim().replace(LINE_BREAK, " ")
        val fence = "`".repeat((BACKTICKS.findAll(flat).maxOfOrNull { it.value.length } ?: 0) + 1)
        val pad = if (flat.startsWith('`') || flat.endsWith('`')) " " else ""
        return "$fence$pad$flat$pad$fence"
    }

    private val LINE_BREAK = Regex("""\s*\R\s*""")
    private val BACKTICKS = Regex("`+")

    private fun StringBuilder.line(text: String = "") {
        append(text).append('\n')
    }
}
